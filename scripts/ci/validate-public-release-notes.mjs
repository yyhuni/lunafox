#!/usr/bin/env node

/**
 * Validate the reviewed, public-safe Markdown body used by one GitHub Release.
 * The same function is consumed by private export checks and the public tree
 * verifier so a retry cannot silently apply a different interpretation.
 */

import crypto from "node:crypto";
import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const SCRIPT_DIR = path.dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT_DIR = path.resolve(SCRIPT_DIR, "../..");
const RELEASE_NOTES_PREFIX = "release-notes";
const RELEASE_NOTE_EVIDENCE_PREFIX = "release-note-evidence";
const MAX_NOTES_BYTES = 64 * 1024;
const TAG_PATTERN = /^v\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/;
const SHA_PATTERN = /^[0-9a-f]{40}$/i;
const DIGEST_PATTERN = /^[0-9a-f]{64}$/i;
const BILINGUAL_SECTION_NAMES = Object.freeze(["English", "简体中文"]);
const CATEGORIES = new Set(["Added", "Improved", "Fixed", "Security", "Documentation"]);
const FORBIDDEN_EVIDENCE_FIELDS = Object.freeze([
  "provider",
  "providerInput",
  "auditInput",
  "reasoning",
  "prompt",
  "transcript",
  "credentials",
  "messages",
]);
const EVIDENCE_SECRET_PATTERNS = Object.freeze([
  /\b(?:gh[pousr]_[A-Za-z0-9_]{20,}|github_pat_[A-Za-z0-9_]{20,})\b/i,
  /-----BEGIN [A-Z0-9 ]*PRIVATE KEY-----/i,
  /\bBearer\s+[A-Za-z0-9._~+/=-]{24,}\b/i,
]);
const INTERNAL_PATTERNS = Object.freeze([
  { code: "private-repository-reference", pattern: /lunafox-private|yyhuni\/lunafox-private/i },
  { code: "private-workflow-reference", pattern: /\.github\/workflows\/release\.ya?ml|refs\/tags\/\*/i },
  { code: "credential-reference", pattern: /\b(?:GITHUB_TOKEN|GH_TOKEN|DOCKERHUB_TOKEN|COSIGN_PRIVATE_KEY|[A-Z][A-Z0-9_]*_PAT)\b|\bsecrets\.[A-Za-z_][A-Za-z0-9_]*/ },
  { code: "internal-release-marker", pattern: /PUBLIC_(?:EXPORT_MANIFEST|PROVENANCE)|chore\((?:export|deploy|workflow)\)|deployment snapshot/i },
  { code: "generated-note-marker", pattern: /(?:generated by|AI-generated|OpenAI|provider response|source(?:-| )id\s*:)/i },
]);

class ReleaseNotesValidationError extends Error {
  constructor(code, message) {
    super(message);
    this.name = "ReleaseNotesValidationError";
    this.code = code;
  }
}

function fail(code, message) {
  throw new ReleaseNotesValidationError(code, message);
}

function parseArgs(argv) {
  const options = {
    rootDir: DEFAULT_ROOT_DIR,
    tag: "",
    notesFile: "",
    evidenceFile: "",
    expectedTargetRevision: "",
    expectedBaselineCommit: "",
    expectedCandidateCommit: "",
    expectedTagCommit: "",
    json: false,
  };
  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    if (arg === "--json") {
      options.json = true;
      continue;
    }
    if (arg === "--help" || arg === "-h") {
      process.stdout.write(usage());
      process.exit(0);
    }
    if (!["--root-dir", "--tag", "--notes-file", "--evidence-file", "--expected-target-revision", "--expected-baseline-commit", "--expected-candidate-commit", "--expected-tag-commit"].includes(arg)) fail("invalid-argument", `unknown argument: ${arg}`);
    const value = argv[index + 1];
    if (!value || value.startsWith("--")) fail("invalid-argument", `${arg} requires a value`);
    if (arg === "--root-dir") options.rootDir = path.resolve(value);
    else if (arg === "--tag") options.tag = value;
    else if (arg === "--notes-file") options.notesFile = value;
    else if (arg === "--evidence-file") options.evidenceFile = value;
    else if (arg === "--expected-target-revision") options.expectedTargetRevision = value;
    else if (arg === "--expected-baseline-commit") options.expectedBaselineCommit = value;
    else if (arg === "--expected-candidate-commit") options.expectedCandidateCommit = value;
    else if (arg === "--expected-tag-commit") options.expectedTagCommit = value;
    index += 1;
  }
  if (!options.tag) fail("missing-tag", "--tag is required");
  return options;
}

function usage() {
  return "Usage: node scripts/ci/validate-public-release-notes.mjs --tag <tag> [--root-dir <dir>] [--notes-file <path>] [--evidence-file <path>] [--expected-target-revision <sha>] [--expected-baseline-commit <sha>] [--expected-candidate-commit <sha>] [--expected-tag-commit <sha>] [--json]\n";
}

function expectedNotesPath(tag) {
  if (!TAG_PATTERN.test(tag)) fail("invalid-tag", `invalid release tag: ${tag}`);
  return `${RELEASE_NOTES_PREFIX}/${tag}.md`;
}

function normalizeNotesPath(value) {
  if (typeof value !== "string" || !value || value.includes("\\") || value.startsWith("/") || value.includes("\0")) {
    fail("invalid-notes-path", "notes file must be a relative POSIX path");
  }
  const normalized = path.posix.normalize(value);
  if (normalized !== value || normalized === "." || normalized.startsWith("../") || normalized.includes("/../")) {
    fail("invalid-notes-path", `notes file is not contained: ${value}`);
  }
  return normalized;
}

function decodeUtf8(bytes, relativePath) {
  try {
    return new TextDecoder("utf-8", { fatal: true }).decode(bytes);
  } catch (error) {
    fail("invalid-utf8", `${relativePath} is not valid UTF-8: ${error.message}`);
  }
}

function extractBilingualSections(text, relativePath = "release notes") {
  const headings = [...text.matchAll(/^##[ \t]+(English|简体中文)[ \t]*$/gmu)];
  const sections = {};
  for (const heading of headings) {
    const name = heading[1];
    if (sections[name]) fail("duplicate-language-section", `${relativePath} contains duplicate ## ${name} sections`);
    const nextHeading = /^##[ \t]+[^\n]+$/gmu;
    nextHeading.lastIndex = heading.index + heading[0].length;
    const next = nextHeading.exec(text);
    const body = text.slice(heading.index + heading[0].length, next?.index ?? text.length).trim();
    sections[name] = { present: true, nonEmpty: Boolean(body) };
    if (!body) fail("empty-language-section", `${relativePath} has an empty ## ${name} section`);
  }
  for (const name of BILINGUAL_SECTION_NAMES) {
    if (!sections[name]) fail("missing-language-section", `${relativePath} is missing required ## ${name} section`);
  }
  return sections;
}

function validateReleaseNotes({ rootDir = DEFAULT_ROOT_DIR, tag, notesFile = "" } = {}) {
  const relativePath = expectedNotesPath(tag);
  if (notesFile && normalizeNotesPath(notesFile) !== relativePath) {
    fail("tag-path-mismatch", `release notes path must be ${relativePath}, got ${notesFile}`);
  }
  const root = fs.realpathSync(rootDir);
  const absolutePath = path.join(root, ...relativePath.split("/"));
  let stat;
  try {
    stat = fs.lstatSync(absolutePath);
  } catch (error) {
    fail("missing-notes", `missing release notes for ${tag}: ${relativePath}`);
  }
  if (!stat.isFile() || stat.isSymbolicLink()) fail("not-regular-file", `${relativePath} must be a regular file`);
  const bytes = fs.readFileSync(absolutePath);
  if (bytes.length > MAX_NOTES_BYTES) fail("notes-too-large", `${relativePath} exceeds ${MAX_NOTES_BYTES} bytes`);
  const text = decodeUtf8(bytes, relativePath);
  if (!text.trim()) fail("notes-empty", `${relativePath} must not be empty`);
  if (/[\u0000-\u0008\u000B\u000C\u000E-\u001F\u007F]/u.test(text)) {
    fail("control-character", `${relativePath} contains an unsupported control character`);
  }
  for (const { code, pattern } of INTERNAL_PATTERNS) {
    if (pattern.test(text)) fail(code, `${relativePath} contains a blocked internal marker (${code})`);
  }
  const bilingualSections = extractBilingualSections(text, relativePath);
  return {
    schemaVersion: 1,
    passed: true,
    releaseTag: tag,
    notesPath: relativePath,
    bytes: bytes.length,
    sha256: crypto.createHash("sha256").update(bytes).digest("hex"),
    bilingualSections,
  };
}

function normalizeEvidencePath(value, tag) {
  const expected = `${RELEASE_NOTE_EVIDENCE_PREFIX}/${tag}.json`;
  if (typeof value !== "string" || !value || value.includes("\\") || value.startsWith("/") || value.includes("\0")) {
    fail("invalid-evidence-path", "evidence file must be a relative POSIX path");
  }
  const normalized = path.posix.normalize(value);
  if (normalized !== value || normalized !== expected || normalized.startsWith("../")) {
    fail("evidence-path-mismatch", `evidence path must be ${expected}, got ${value}`);
  }
  return normalized;
}

function validateSha(value, field) {
  if (!SHA_PATTERN.test(String(value ?? ""))) fail("invalid-evidence-identity", `${field} must be a 40-character commit SHA`);
  return String(value).toLowerCase();
}

function assertTargetIsReachable(rootDir, targetRevision, candidateCommit, candidateLabel) {
  try {
    execFileSync("git", ["-C", rootDir, "merge-base", "--is-ancestor", targetRevision, candidateCommit], {
      stdio: ["ignore", "ignore", "pipe"],
    });
  } catch (error) {
    fail("stale-evidence", `candidate target revision is not an ancestor of the ${candidateLabel}: ${error.stderr?.toString().trim() || "merge-base check failed"}`);
  }
}

function normalizeDigest(value, field) {
  if (!DIGEST_PATTERN.test(String(value ?? ""))) fail("invalid-evidence-digest", `${field} must be a SHA-256 digest`);
  return String(value).toLowerCase();
}

function sameClaimTokens(left, right) {
  if (!Array.isArray(left) || !Array.isArray(right) || left.some((value) => typeof value !== "string") || right.some((value) => typeof value !== "string")) {
    fail("invalid-evidence-entries", "candidate evidence claim tokens must be string arrays");
  }
  return JSON.stringify([...left].sort()) === JSON.stringify([...right].sort());
}

function findForbiddenEvidenceField(value, path = "evidence") {
  if (Array.isArray(value)) {
    for (let index = 0; index < value.length; index += 1) {
      const found = findForbiddenEvidenceField(value[index], `${path}[${index}]`);
      if (found) return found;
    }
    return "";
  }
  if (!value || typeof value !== "object") return "";
  for (const [field, nested] of Object.entries(value)) {
    const fieldPath = `${path}.${field}`;
    if (FORBIDDEN_EVIDENCE_FIELDS.includes(field)) return fieldPath;
    const found = findForbiddenEvidenceField(nested, fieldPath);
    if (found) return found;
  }
  return "";
}

/**
 * Verify the private source-tree evidence that binds notes to one candidate.
 * Public export callers intentionally do not pass an evidence path.
 */
function validateCandidateEvidence({
  rootDir = DEFAULT_ROOT_DIR,
  tag,
  evidenceFile = "",
  expectedTargetRevision = "",
  expectedBaselineCommit = "",
  expectedCandidateCommit = "",
  expectedTagCommit = "",
  notesFile = "",
} = {}) {
  const relativeEvidencePath = normalizeEvidencePath(evidenceFile || `${RELEASE_NOTE_EVIDENCE_PREFIX}/${tag}.json`, tag);
  const root = fs.realpathSync(rootDir);
  const evidencePath = path.join(root, ...relativeEvidencePath.split("/"));
  let evidence;
  try {
    evidence = JSON.parse(fs.readFileSync(evidencePath, "utf8"));
  } catch (error) {
    fail("missing-evidence", `missing or invalid candidate evidence: ${relativeEvidencePath}`);
  }
  if (!evidence || evidence.schemaVersion !== 2 || evidence.status !== "validated") {
    fail("invalid-evidence", "candidate evidence schema/status is invalid");
  }
  const identity = evidence.identity;
  if (!identity || identity.tag !== tag || !SHA_PATTERN.test(identity.baselineCommit ?? "") || !SHA_PATTERN.test(identity.targetRevision ?? "")) {
    fail("invalid-evidence-identity", "candidate evidence identity is invalid or does not match the release tag");
  }
  identity.baselineCommit = validateSha(identity.baselineCommit, "baselineCommit");
  identity.targetRevision = validateSha(identity.targetRevision, "targetRevision");
  if (expectedTargetRevision && identity.targetRevision !== validateSha(expectedTargetRevision, "expectedTargetRevision")) {
    fail("stale-evidence", "candidate evidence target revision does not match the release commit");
  }
  if (expectedBaselineCommit && identity.baselineCommit !== validateSha(expectedBaselineCommit, "expectedBaselineCommit")) {
    fail("stale-evidence", "candidate evidence baseline commit does not match the resolved baseline");
  }
  if (expectedCandidateCommit) {
    const candidateCommit = validateSha(expectedCandidateCommit, "candidateCommit");
    assertTargetIsReachable(root, identity.targetRevision, candidateCommit, "candidate head commit");
  }
  if (expectedTagCommit) {
    const tagCommit = validateSha(expectedTagCommit, "tagCommit");
    assertTargetIsReachable(root, identity.targetRevision, tagCommit, "Tag commit");
  }
  if (typeof evidence.baselineRelease !== "string" || !evidence.baselineRelease.trim() || /[\r\n]/.test(evidence.baselineRelease)) {
    fail("invalid-evidence-baseline", "candidate evidence baselineRelease must be a non-empty single line");
  }
  if (!Array.isArray(evidence.coverage?.included) || !Array.isArray(evidence.coverage?.excluded) ||
      !Array.isArray(evidence.coverage?.unmapped) || !Array.isArray(evidence.coverage?.failed) ||
      evidence.coverage.unmapped.length > 0 || evidence.coverage.failed.length > 0) {
    fail("incomplete-evidence", "candidate evidence contains unmapped or failed source records");
  }
  const coverageStates = ["included", "excluded", "unmapped", "failed"];
  const covered = new Set();
  for (const state of coverageStates) {
    for (const item of evidence.coverage[state]) {
      if (!item || typeof item.sourceId !== "string" || !item.sourceId.trim() || covered.has(item.sourceId)) {
        fail("invalid-evidence-coverage", "candidate evidence coverage contains missing or duplicate source IDs");
      }
      if (!Array.isArray(item.commitShas) || item.commitShas.length === 0 || item.commitShas.some((sha) => !SHA_PATTERN.test(String(sha)))) {
        fail("invalid-evidence-coverage", "candidate evidence commitShas must contain valid commit SHAs");
      }
      if (state === "included" && !CATEGORIES.has(item.category)) {
        fail("invalid-evidence-coverage", "included candidate evidence records require a supported category");
      }
      if (state !== "included" && (typeof item.reason !== "string" || !item.reason.trim())) {
        fail("invalid-evidence-coverage", "excluded, unmapped, and failed candidate evidence records require a reason");
      }
      covered.add(item.sourceId);
    }
  }
  if (!Array.isArray(evidence.sourceIds) || evidence.sourceIds.some((sourceId) => typeof sourceId !== "string")) {
    fail("invalid-evidence-sources", "candidate evidence sourceIds must be a string array");
  }
  if (new Set(evidence.sourceIds).size !== evidence.sourceIds.length) {
    fail("invalid-evidence-sources", "candidate evidence sourceIds must be unique");
  }
  for (const sourceId of evidence.sourceIds) {
    if (!covered.has(sourceId)) fail("incomplete-evidence", `candidate evidence does not cover source ${sourceId}`);
  }
  if (covered.size !== evidence.sourceIds.length) {
    fail("invalid-evidence-sources", "candidate evidence sourceIds must exactly match coverage records");
  }
  if (!Array.isArray(evidence.commitSourceIds) || evidence.commitSourceIds.some((sourceId) => typeof sourceId !== "string" || !sourceId.trim())) {
    fail("invalid-evidence-commits", "candidate evidence commitSourceIds must be a string array");
  }
  if (new Set(evidence.commitSourceIds).size !== evidence.commitSourceIds.length) {
    fail("invalid-evidence-commits", "candidate evidence commitSourceIds must be unique");
  }
  if (!Array.isArray(evidence.commitInventory)) fail("invalid-evidence-commits", "candidate evidence commitInventory must be an array");
  const commitSourceIds = evidence.commitSourceIds;
  const inventoryIds = new Set();
  const inventoryShas = new Set();
  for (const item of evidence.commitInventory) {
    if (!item || typeof item.sourceId !== "string" || inventoryIds.has(item.sourceId)) {
      fail("invalid-evidence-commits", "candidate evidence commitInventory contains duplicate or missing source IDs");
    }
    const sha = validateSha(item.sha, "commitInventory.sha");
    if (!Array.isArray(item.recordSourceIds) || item.recordSourceIds.length === 0 || item.recordSourceIds.some((sourceId) => !covered.has(sourceId))) {
      fail("invalid-evidence-commits", "commitInventory recordSourceIds must refer to covered records");
    }
    inventoryIds.add(item.sourceId);
    inventoryShas.add(sha);
  }
  if (inventoryIds.size !== commitSourceIds.length || commitSourceIds.some((sourceId) => !inventoryIds.has(sourceId))) {
    fail("invalid-evidence-commits", "commitSourceIds and commitInventory do not describe the same commits");
  }
  const coveredShas = new Set(Object.values(evidence.coverage).flatMap((items) => items.flatMap((item) => item.commitShas ?? [])));
  for (const sha of inventoryShas) {
    if (!coveredShas.has(sha)) fail("incomplete-evidence", `candidate evidence does not cover commit ${sha}`);
  }
  const factsDigest = normalizeDigest(evidence.factsDigest, "factsDigest");
  const auditDigest = normalizeDigest(evidence.auditDigest, "auditDigest");
  const notesDigest = normalizeDigest(evidence.notesDigest, "notesDigest");
  const forbiddenField = findForbiddenEvidenceField(evidence);
  if (forbiddenField) {
    fail("forbidden-evidence-provenance", `candidate evidence must not persist ${forbiddenField}`);
  }
  if (EVIDENCE_SECRET_PATTERNS.some((pattern) => pattern.test(JSON.stringify(evidence)))) {
    fail("forbidden-evidence-provenance", "candidate evidence must not persist a credential");
  }
  if (!evidence.agentAudit || evidence.agentAudit.schemaVersion !== 1 || evidence.agentAudit.mode !== "release-executor") {
    fail("invalid-evidence-audit", "candidate evidence must contain release-executor audit provenance");
  }
  if (Object.keys(evidence.agentAudit).some((field) => !["schemaVersion", "mode", "factsDigest", "digest"].includes(field))) {
    fail("invalid-evidence-audit", "candidate evidence audit provenance contains an unsupported field");
  }
  if (normalizeDigest(evidence.agentAudit.factsDigest, "agentAudit.factsDigest") !== factsDigest ||
      normalizeDigest(evidence.agentAudit.digest, "agentAudit.digest") !== auditDigest) {
    fail("invalid-evidence-audit", "candidate evidence audit provenance does not match its digests");
  }
  if (!Array.isArray(evidence.entries)) fail("invalid-evidence-entries", "candidate evidence entries must be an array");
  const entryBySource = new Map();
  for (const entry of evidence.entries) {
    if (!entry || !CATEGORIES.has(entry.category) || !Array.isArray(entry.sourceIds) || entry.sourceIds.length === 0) {
      fail("invalid-evidence-entries", "candidate evidence entries require source IDs and a supported category");
    }
    if (!sameClaimTokens(entry.claims?.english, entry.claims?.chinese)) {
      fail("bilingual-mismatch", "candidate evidence bilingual claim tokens differ");
    }
    for (const sourceId of entry.sourceIds) {
      if (typeof sourceId !== "string" || entryBySource.has(sourceId) || !covered.has(sourceId)) {
        fail("invalid-evidence-entries", "candidate evidence entries contain an unknown or duplicate source ID");
      }
      entryBySource.set(sourceId, entry);
    }
  }
  for (const included of evidence.coverage.included) {
    const entry = entryBySource.get(included.sourceId);
    if (!entry || entry.category !== included.category) {
      fail("incomplete-evidence", `candidate evidence does not bind included source ${included.sourceId} to its rendered category`);
    }
  }
  for (const [sourceId] of entryBySource) {
    if (!evidence.coverage.included.some((item) => item.sourceId === sourceId)) {
      fail("invalid-evidence-entries", "candidate evidence entries must only cover included sources");
    }
  }
  const notes = validateReleaseNotes({ rootDir, tag, notesFile });
  if (notes.sha256 !== notesDigest) fail("notes-evidence-mismatch", "candidate evidence notesDigest does not match the notes file");
  return {
    schemaVersion: 1,
    passed: true,
    evidencePath: relativeEvidencePath,
    identity,
    factsDigest,
    auditDigest,
    notesDigest,
    coverage: evidence.coverage,
    sourceIds: evidence.sourceIds,
    commitSourceIds,
    candidateCommit: expectedCandidateCommit ? validateSha(expectedCandidateCommit, "candidateCommit") : undefined,
    tagCommit: expectedTagCommit ? validateSha(expectedTagCommit, "tagCommit") : undefined,
  };
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const result = options.evidenceFile || options.expectedTargetRevision || options.expectedBaselineCommit || options.expectedCandidateCommit || options.expectedTagCommit
    ? validateCandidateEvidence(options)
    : validateReleaseNotes(options);
  process.stdout.write(`${options.json ? JSON.stringify(result, null, 2) : `release notes verified: ${result.notesPath} (${result.bytes} bytes)`}\n`);
  return result;
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  try {
    main();
  } catch (error) {
    process.stderr.write(`release notes validation failed: ${error.message}\n`);
    process.exitCode = 1;
  }
}

