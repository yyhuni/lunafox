import { describe, expect, it } from "vitest"
import { existsSync, readFileSync } from "node:fs"
import path from "node:path"

const browserEntryPath = path.resolve(process.cwd(), "mock/browser.ts")
const serverEntryPath = path.resolve(process.cwd(), "mock/server.ts")
const scenarioEntryPath = path.resolve(process.cwd(), "mock/scenarios/index.ts")
const handlersEntryPath = path.resolve(process.cwd(), "mock/handlers/index.ts")

describe("mock platform contract", () => {
  it("exposes browser and node entrypoints for MSW", () => {
    expect(existsSync(browserEntryPath)).toBe(true)
    expect(existsSync(serverEntryPath)).toBe(true)
  })

  it("defines a shared scenario registry and handler registry", () => {
    expect(existsSync(scenarioEntryPath)).toBe(true)
    expect(existsSync(handlersEntryPath)).toBe(true)
  })

  it("documents browser MSW bootstrap through setupWorker", () => {
    const source = readFileSync(browserEntryPath, "utf8")
    expect(source).toContain("setupWorker")
    expect(source).toContain("mockHandlers")
    expect(source).toContain('import("msw/browser")')
    expect(source).not.toContain('import { setupWorker } from "msw/browser"')
  })

  it("documents node MSW bootstrap through setupServer", () => {
    const source = readFileSync(serverEntryPath, "utf8")
    expect(source).toContain("setupServer")
    expect(source).toContain("mockHandlers")
  })

  it("keeps mock REST paths aligned with production service URLs used by smoke tests", () => {
    const source = readFileSync(handlersEntryPath, "utf8")
    expect(source).toContain('path === "/scanWorkflows"')
    expect(source).toContain('path.match(/^\\/scanWorkflows\\/([^/]+)\\/profile$/)')
    expect(source).not.toContain('path === "/scanWorkflowProfiles"')
    expect(source).not.toContain('path === "/workflows/profiles"')
    expect(source).toContain('path === "/nucleiPocSources/current"')
    expect(source).toContain('path === "/nucleiPocSources:sync"')
    expect(source).toContain('path.match(/^\\/nucleiPocSyncTasks\\/([^/]+)$/)')
    expect(source).toContain('path === "/nucleiPocs"')
    expect(source).toContain('path === "/nucleiPocs:setActivation"')
    expect(source).toContain('path.match(/^\\/nucleiPocs\\/([^/]+)$/)')
    expect(source).not.toContain('path.match(/^\\/nuclei\\/repos\\/')
    expect(source).toContain('path === "/targets:batchDelete"')
    expect(source).toMatch(/path === "\/targets"[\s\S]*orderBy: url\.searchParams\.get\("orderBy"\)/)
    expect(source).not.toContain('path === "/targets/bulk-delete"')
    expect(source).toContain('method === "DELETE" && targetMatch')
    expect(source).toContain('path === "/organizations:batchDelete"')
    expect(source).not.toContain('path === "/organizations/bulk-delete"')
    expect(source).toContain('method === "DELETE" && organizationMatch')
    expect(source).toContain('path === "/websites:batchDelete"')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/websites:batchCreate$/)')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/websites\\/exportFiles\\/current$/)')
    expect(source).toContain('method === "DELETE" && websiteMatch')
    expect(source).toContain('path === "/directories:batchDelete"')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/directories\\/filterOptions$/)')
    expect(source).toContain('path.match(/^\\/scans\\/(\\d+)\\/directories\\/filterOptions$/)')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/directories:batchCreate$/)')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/directories\\/exportFiles\\/current$/)')
    expect(source).toContain('method === "DELETE" && directoryMatch')
    expect(source).toContain('path === "/subdomains:batchDelete"')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/subdomains:batchCreate$/)')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/subdomains\\/exportFiles\\/current$/)')
    expect(source).toContain('method === "DELETE" && subdomainDeleteMatch')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/hostPorts$/)')
    expect(source).toContain('path.match(/^\\/scans\\/(\\d+)\\/hostPorts$/)')
    expect(source).toContain('path === "/hostPorts:batchDelete"')
    expect(source).not.toContain('host-ports')
    expect(source).toContain('path === "/endpoints:batchDelete"')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/endpoints:batchCreate$/)')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/endpoints\\/exportFiles\\/current$/)')
    expect(source).toContain('method === "DELETE" && endpointMatch')
    expect(source).toContain('path === "/scans/deletions"')
    expect(source).toContain('path === "/scanStatistics"')
    expect(source).toContain('path === "/scans:batchCreate"')
    expect(source).toContain('path === "/scans:batchStop"')
    expect(source).toContain('path === "/scans:quickCreate"')
    expect(source).toContain('isScanInputSource(body.inputSource)')
    expect(source).not.toContain('path === "/scans/stats"')
    expect(source).toContain('method === "DELETE" && scanMatch')
    expect(source).toContain('path === "/screenshots:batchDelete"')
    expect(source).not.toContain('path === "/screenshots/bulk-delete"')
    expect(source).toContain('path === "/vulnerabilities:batchDelete"')
    expect(source).toContain('path === "/vulnerabilities:batchUpdate"')
    expect(source).toContain('path === "/vulnerabilityStatistics"')
    expect(source).toContain('path.match(/^\\/targets\\/(\\d+)\\/vulnerabilityStatistics$/)')
    expect(source).toContain('path === "/admin/system/runtimeMetrics/current"')
    expect(source).toContain('path === "/admin/agents/filterOptions"')
    expect(source).toContain('path === "/admin/agentClusterSummaries/current"')
    expect(source).toContain('path === "/admin/agentLocationMaps/current"')
    expect(source).toContain('path === "/admin/agentRegistrationTokens"')
    expect(source).toContain('path.match(/^\\/admin\\/agentRegistrationTokens\\/(\\d+)$/)')
    expect(source).not.toContain('path === "/admin/agents/registrationTokens"')
    expect(source).toMatch(/path === "\/admin\/agents"[\s\S]*pageToken: url\.searchParams\.get\("pageToken"\)/)
    expect(source).toMatch(/path === "\/admin\/agents"[\s\S]*filter: url\.searchParams\.get\("filter"\)/)
    expect(source).toMatch(/path === "\/admin\/agents"[\s\S]*orderBy: url\.searchParams\.get\("orderBy"\)/)
    expect(source).not.toContain('url.searchParams.get("status") || undefined')
    expect(source).not.toContain('path === "/vulnerabilities/bulk-delete"')
    expect(source).not.toContain('path === "/vulnerabilities/stats"')
    expect(source).toContain('path === "/scheduledScans"')
    expect(source).toContain('path === "/scheduledScans:summarize"')
    expect(source).toContain('path.match(/^\\/scheduledScans\\/(\\d+)$/)')
    expect(source).not.toContain('scheduled-scans')
    expect(source).toContain('method === "DELETE" && scheduledScanMatch')
    expect(source).toContain('method === "DELETE" && agentNodeMatch')
  })

  it("keeps AIP organization pagination metadata for picker pagination", () => {
    const source = readFileSync(handlersEntryPath, "utf8")

    expect(source).toContain("function toAipOrganizationsResponse")
    expect(source).toContain("totalSize: response.total")
    expect(source).toContain("const page = response.page ?? 1")
    expect(source).toContain("const pageSize = response.pageSize ?? 10")
    expect(source).toContain("const totalPages = response.totalPages ?? Math.ceil(response.total / pageSize)")
    expect(source).toContain("nextPageToken: `mock-organization-page-${nextPage}`")
    expect(source).toContain('parseMockPageToken(url.searchParams.get("pageToken"), "mock-organization-page")')
  })
})
